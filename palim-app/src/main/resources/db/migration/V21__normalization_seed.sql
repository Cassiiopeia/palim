-- 늘 비어 있고, 사람이 수백 품목을 눈으로 찾아 손으로 이어야 한다.
--
-- 여기 넣는 것은 **어느 원천에나 통하는 일반적인 다듬기**뿐이다. 특정 거래처의 표기 습관에
-- 맞춘 규칙은 화면에서 추가한다 — 그래야 다른 곳에 가져다 써도 그대로 돈다.
--
-- 공백 제거와 소문자화는 엔진이 항상 하므로 여기 넣지 않는다.

