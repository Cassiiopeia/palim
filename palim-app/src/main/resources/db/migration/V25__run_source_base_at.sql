--
-- 지금은 두 원천이 공유하는 「칸」 시각만 남는다. 그런데 합산은 원천마다 자기 시각으로 하므로
-- (한쪽은 자정, 한쪽은 그날 오후일 수 있다) 칸 시각만으로는 **그 회차가 실제로 본 자료를 다시
-- 불러올 수 없다.**
--
-- 그래서 결과를 나중에 뜯어보려 할 때 — 「이 +11 이 어느 로트에서 나온 건가」 — 지금 담긴
-- 최신 재고로 다시 계산하는 수밖에 없고, 그 사이 수집이 한 번 더 돌았으면 **화면에 적힌 합계와
-- 뜯어본 내역의 합이 어긋난다.** 사람은 둘 중 무엇이 맞는지 알 방법이 없다.
