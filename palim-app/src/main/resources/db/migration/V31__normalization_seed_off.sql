-- 기본으로 켜 둔 이름 다듬기 규칙 중 «로트를 뭉개는» 둘을 꺼 둔다.
--
-- V21 이 심는 네 규칙 가운데 「괄호와 그 안의 내용을 뺀다」·「이름에 박힌 날짜를 뺀다」 는
-- 품목명에 소비기한이 붙어 오는 곳에서는 편하다. 그런데 **소비기한으로만 구분되는 서로 다른
-- 품목**이 있는 곳에서는 그것들을 한 물건으로 만든다.
--
--     제품A 850g (27.03.16)
--     제품A 850g (27.04.16)   →  전부 「제품A850g」
--     제품A 850g (27.04.20)
--
-- 그러면 대조는 「재고가 맞는다」 고 말하는데 실제로는 셋이 합쳐진 것이다. 불일치를 못 찾는
-- 것보다 나쁘다 — **틀렸다는 사실조차 드러나지 않는다.** 실제로 그렇게 관리하는 곳을 확인했다
-- (입고 시점마다 기한이 달라 소비기한별로 별도 품목으로 둔다).
--
-- **「시스템이 알아서 켜 둔 것」 이라 더 위험하다.** 자기가 넣은 규칙이면 결과가 이상할 때 그
-- 규칙을 떠올리지만, 처음부터 있던 것은 존재 자체를 모른다. 그래서 원인을 자기 자료에서 찾게
-- 되고, 찾지 못한다.
--
-- **지우지 않고 끈다.** 소비기한을 이름에 붙이지 않는 곳에서는 여전히 쓸모가 있고, 화면에서
-- 켜면 그대로 동작한다. 켤 때는 무엇이 합쳐지는지 충돌 경고가 보여준다.
--
-- **사람이 이미 손댄 규칙은 건드리지 않는다.** created_at 과 updated_at 이 같다는 것은 심어진
-- 뒤로 아무도 만지지 않았다는 뜻이다. 켜 두기로 «정한» 곳의 판단을 이 마이그레이션이 뒤집으면
-- 그쪽에서는 이유 없이 대조 결과가 바뀐다.
UPDATE normalization_rule
   SET is_active = false,
       updated_at = now()
 WHERE name IN ('괄호와 그 안의 내용을 뺀다', '이름에 박힌 날짜를 뺀다')
   AND is_active = true
   AND created_at = updated_at;
