-- 기본으로 켜 둔 이름 다듬기 규칙 중 «로트를 뭉개는» 둘을 꺼 둔다.
--
-- V21 이 심는 네 규칙 가운데 「괄호와 그 안의 내용을 뺀다」·「이름에 박힌 날짜를 뺀다」 는
-- 품목명에 소비기한이 붙어 오는 곳에서는 편하다. 그런데 **소비기한으로만 구분되는 서로 다른
-- 품목**이 있는 곳에서는 그것들을 한 물건으로 만든다.
--
--     제품A 850g (27.03.16)
--     제품A 850g (27.04.16)   →  전부 「제품A850g」
--     제품A 850g (27.04.20)
--
-- 그러면 대조는 「맞는다」 고 말하는데 실제로는 셋이 합쳐진 것이다. 불일치를 못 찾는 것보다
-- 나쁘다 — **틀렸다는 사실조차 드러나지 않는다.** 실제로 그렇게 관리하는 곳을 확인했다
-- (입고 시점마다 기한이 달라 소비기한별로 별도 품목으로 둔다).
--
-- **「시스템이 알아서 켜 둔 것」 이라 더 위험하다.** 자기가 넣은 규칙이면 결과가 이상할 때 그
-- 규칙을 떠올리지만, 처음부터 있던 것은 존재 자체를 모른다.
--
-- **지우지 않고 끈다.** 소비기한을 이름에 붙이지 않는 곳에서는 여전히 쓸모가 있고, 화면에서
-- 켜면 그대로 동작한다. 켤 때는 무엇이 합쳐지는지 충돌 경고가 알려 준다.
--
-- ── 왜 이름이 아니라 id 로 찾는가 ──────────────────────────────────────────────
--
-- 이름(`name IN (...)`)으로 찾으면 두 가지가 어긋난다.
--
-- 1) **프리셋이 같은 이름을 쓴다.** 화면의 「자주 쓰는 것」 은 「괄호와 그 안의 내용을 뺀다」 를
--    그대로 이름으로 넣는다. 사용자가 규칙을 정리하고 프리셋으로 다시 넣어 둔 상태에서 이
--    마이그레이션이 돌면, 방금 «의도적으로» 넣은 규칙이 이유 없이 꺼진다.
-- 2) 이름은 화면에서 고칠 수 있다. 고친 순간 이 조건은 아무것도 잡지 못한다.
--
-- id 는 V21 이 박아 둔 고정값이라 둘 다 피한다.
--
-- ── 왜 「손댄 적 없는 것만」 조건을 걸지 않는가 ────────────────────────────────
--
-- 처음에는 `created_at = updated_at` 으로 「아무도 안 만진 것만」 끄려 했다. 그런데 그 대리지표는
-- 이미 깨져 있다 — 순서 끌어 옮기기·켬끔 토글이 updated_at 을 갱신하므로, 규칙을 한 번이라도
-- 만진 곳에서는 이 UPDATE 가 **0행을 고치고 조용히 끝난다.** Flyway 는 성공으로 기록하고 로그도
-- 남지 않아, 「껐다」 고 믿는 채로 켜진 상태가 유지된다. 그 침묵이 이 규칙의 위험보다 나쁘다.
UPDATE normalization_rule
   SET is_active  = false,
       updated_at = now()
 WHERE id IN ('01937000-0000-7000-8000-000000000001',   -- 괄호와 그 안의 내용을 뺀다
              '01937000-0000-7000-8000-000000000003')   -- 이름에 박힌 날짜를 뺀다
   AND is_active = true;
