package kr.suhsaechan.palim.notification;

/**
 * 알림 종류.
 *
 * <p>앞의 네 개는 기능 명세서가 정의한 사용자 대상 알림이고, 뒤의 네 개는 시스템 자기 감시
 * 알림이다. 별도 관측 스택(Prometheus 등)을 두지 않는 이유는 이미 운영자에게 도달하는 경로가
 * 있기 때문이다 — 시스템 장애도 같은 경로로 보낸다(설계서 9.3).
 */
public enum NotificationType {

    /** 신규 주문 (F-02). */
    NEW_ORDER("신규 주문"),

    /** 안전재고 미달 (F-05). */
    LOW_STOCK("재고 부족"),

    /** 재고 0 도달 — 긴급 (F-05). */
    OUT_OF_STOCK("품절"),

    /**
     * 오버셀링 — 실재고를 초과해 판매되어 재고가 음수가 되었다.
     *
     * <p>채널 재고 동기화 지연 중에 발생한다. 출고 불가 상태이므로 발주자가 즉시 조치해야 한다.
     */
    OVERSELL("초과판매"),

    /** 미매핑 상품 주문 수집 (F-04). 방치하면 재고가 조용히 틀어진다. */
    UNMAPPED_PRODUCT("미매핑 상품"),

    /** 일일 요약 리포트 (F-06). */
    DAILY_REPORT("일일 리포트"),

    /** 채널 수집 연속 실패 (A-10). */
    COLLECT_FAILURE("수집 실패"),

    /** 채널 재고 전송 실패·차단 (F-08). */
    STOCK_PUSH_FAILURE("재고 전송 실패"),

    /**
     * 재고 스냅샷과 이력 누적합 불일치 (설계서 5.3).
     *
     * <p><b>동결 도메인 전용이다.</b> 한 시스템 «안에서» 기준값과 변동 이력이 어긋난 것을
     * 말한다. 두 시스템 «사이» 를 견주는 대조와는 다른 사건이므로 섞어 쓰지 않는다 —
     * 실제로 섞여 있었고, 받는 쪽이 형식을 하나만 알아서 대조 알림이 빈 값으로 나갔다.
     */
    STOCK_MISMATCH("재고 불일치"),

    /**
     * 두 시스템의 재고가 어긋났다.
     *
     * <p>{@link #STOCK_MISMATCH} 와 다른 사건이다. 저쪽은 «한 시스템 안에서» 기준값과 이력이
     * 안 맞는 것이고, 이것은 «전산과 실물» 처럼 서로 다른 두 곳의 수량이 안 맞는 것이다.
     * 고칠 곳도 다르다 — 저쪽은 이력을 뒤지고, 이쪽은 어느 쪽이 맞는지부터 정해야 한다.
     */
    RECONCILE_MISMATCH("재고 대조 차이"),

    /**
     * 대조가 <b>여러 날 연속으로 돌지 못했다.</b>
     *
     * <p>하루 못 돈 것은 알리지 않는다 — 수집이 늦으면 기준 시각이 어긋나고, 그것은 다음
     * 회차에 저절로 풀린다. 매일 알리면 늦은 날마다 알림이 가서 사람이 알림을 꺼 버린다.
     *
     * <p>그런데 <b>영영 안 풀리는 실패</b>도 같은 모양이다. 설정이 깨졌거나 한쪽 수집이 멈춘
     * 경우인데, 지금까지는 로그에만 남아 <b>아무도 몰랐다.</b> 며칠 연속이면 「다시 하면 되는
     * 일」 이 아니므로 그때 한 번 알린다.
     */
    RECONCILE_BLOCKED("대조가 막힘"),

    /**
     * 라이징 인플루언서 주간 요약 (#43).
     *
     * <p>라이징은 <b>유통기한이 있는 정보</b>다 — 조회수가 먼저 터지고 구독자·단가가 따라오는
     * 시차 안에서만 값이 있고, 2주 늦으면 이미 단가가 올라 있다. 화면을 열지 않아도 기회가
     * 먼저 도달하도록 알림으로 민다.
     */
    RISING_INFLUENCER("라이징 인플루언서"),

    /**
     * 재고 대조 하루 요약 (#173).
     *
     * <p><b>이상이 없어도 보낸다.</b> 지금까지는 이상이 없으면 아무것도 오지 않았는데, 그 무음이
     * 「오늘 깨끗함」·「전부 첫 관찰이라 보류」·「알릴 기준을 안 정함」·「대조가 며칠째 막힘」·
     * 「보낼 곳이 연결 안 돼 쌓이는 중」 을 <b>동시에</b> 뜻했다.
     *
     * <p>그래서 「열지 않아도 오늘 볼 일이 있는지 판단한다」 가 성립하지 않았다. 매일 오고,
     * 제목이 상태를 말해야 그 판단이 선다.
     */
    RECONCILE_DIGEST("재고 대조 요약");

    private final String displayName;

    NotificationType(String displayName) {
        this.displayName = displayName;
    }

    /** 화면·메시지 표시 이름. */
    public String displayName() {
        return displayName;
    }

    /**
     * 긴급 알림 여부.
     *
     * <p>긴급 알림은 <b>야간 보류와 묶음 발송에서 제외</b>된다. 재고가 음수가 되었거나 수집이
     * 멈춘 상황은 아침까지 기다릴 수 없다. 발주자가 알림 과다를 우려해 야간 보류를 켰더라도,
     * 매출 손실로 직결되는 사안은 즉시 알려야 한다.
     */
    public boolean isUrgent() {
        return this == OVERSELL
                || this == OUT_OF_STOCK
                || this == COLLECT_FAILURE
                || this == STOCK_PUSH_FAILURE
                || this == STOCK_MISMATCH;
        // 대조 알림 둘은 긴급이 아니다. 매일 아침 도는 일이고, 차이는 오늘 안에 손보면
        // 되는 종류다. 긴급으로 두면 야간 보류를 켠 사람에게 새벽에 울린다.
    }

    /**
     * 묶음 발송 대상 여부.
     *
     * <p>주문 알림만 묶는다. 주문량이 많을 때 알림 과다로 아예 확인하지 않게 되는 문제를
     * 막기 위한 기능이므로(F-02), 빈도가 낮은 다른 알림은 묶을 이유가 없다.
     */
    public boolean isBatchable() {
        return this == NEW_ORDER;
    }
}
